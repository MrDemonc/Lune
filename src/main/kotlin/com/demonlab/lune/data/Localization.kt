enum class AppLanguage(val code: String, val displayName: String, val nativeName: String) {
    SYSTEM("system", "System Default", "System"),
    ENGLISH("en", "English", "English"),
    SPANISH("es", "Spanish", "Español"),
    PORTUGUESE("pt", "Portuguese", "Português"),
    FRENCH("fr", "French", "Français"),
    GERMAN("de", "German", "Deutsch"),
    RUSSIAN("ru", "Russian", "Русский"),
    CHINESE("zh", "Chinese", "中文"),
    PERSIAN("fa", "Persian", "فارسی");

    companion object {
        fun fromCode(code: String): AppLanguage {
            return entries.find { it.code.equals(code, ignoreCase = true) } ?: SYSTEM
        }
    }
}

object L10n {
    val currentLanguage: String
        get() {
            val configured = SettingsManager.instance.language
            if (configured.isNotBlank() && configured != "system") {
                return configured
            }
            val sysLang = Locale.getDefault().language.lowercase()
            return when {
                sysLang.startsWith("es") -> "es"
                sysLang.startsWith("pt") -> "pt"
                sysLang.startsWith("fr") -> "fr"
                sysLang.startsWith("de") -> "de"
                sysLang.startsWith("ru") -> "ru"
                sysLang.startsWith("zh") -> "zh"
                sysLang.startsWith("fa") -> "fa"
                else -> "en"
            }
        }

    fun get(key: String): String {
        val lang = currentLanguage
        val langMap = translations[lang] ?: translations["en"] ?: emptyMap()
        return langMap[key] ?: translations["en"]?.get(key) ?: key
    }

